#!/usr/bin/env node
// Writes the check results of tests/results/<id>.json into the RESULTS block of systems/<folder>/spec.md.
// Usage: node record-results.mjs p1 [c9 ...]   (run `npm test` first)
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { SKILL_DIR, designDir, readJson } from './lib/util.mjs';

const START = '<!-- RESULTS:START (generated by scripts/record-results.mjs; do not edit by hand) -->', END = '<!-- RESULTS:END -->';
const mark = (b) => (b ? 'pass' : '**FAIL**');
export function table(r) {
  const c = r.checks, lowest = (rows) => rows.reduce((m, x) => (x.ratio / x.min < m.ratio / m.min ? x : m));
  const con = lowest(c.contrast.contrast), cb = c.contrast.colourBlindWorst;
  const ex = Object.entries(c.extraction.samples), fit = c.fit;
  const rows = [
    ['1 WCAG AA contrast and colour-blind', mark(c.contrast.pass), `Lowest text/non-text pair ${con.pair} ${con.ratio}:1 (needs ${con.min}); worst under ${cb.kind} ${cb.pair} ${cb.ratio}:1. Every pair is also checked under protanopia, deuteranopia and tritanopia.`],
    ['2 Greyscale print', mark(c.greyscale.pass), `Token pairs recomputed in greyscale and ${c.greyscale.rendered.items} rendered text runs measured on a greyscale raster; lowest ${c.greyscale.rendered.worst.ratio}:1 (needs 4.5).`],
    ['3 Render tests', mark(c.render.pass), `Latin, Arabic (RTL), Sorani, Chinese, Devanagari, Cyrillic samples: no missing glyphs, no banned graphics. Sorani letters ڕ ڵ ۆ ێ ە present in ${[...new Set(c.render.sorani.map((s) => s.font))].join(', ')}.`],
    ['4 PDF text extraction', mark(c.extraction.pass), `${ex.filter(([, e]) => e.ok).length}/${ex.length} sample PDFs (design and A twin) extract headings in reading order with email in the text.`],
    ['5 Page fit', mark(c.fit.pass), `Short profile: ${fit.short.pages} page, ${Math.round(fit.short.fill * 100)}% of the page height used (Arabic ${Math.round(fit.shortArabic.fill * 100)}%). Long profile: ${fit.long.pages} pages, bottom margin clear, last bullet present.`],
  ];
  const docx = r.docx.status.startsWith('pass') ? `pass (${r.docx.tier === 'C' ? 'best effort, single column' : 'A/B'}; LibreOffice only, not verified in Word)` : r.docx.status;
  const twin = r.twin ? `A twin ${r.twin.design}: ${r.twin.produced ? 'produced for every sample' : '**NOT produced**'}.` : 'Tier A: no twin needed.';
  return [START, '| Check | Result | Detail |', '|---|---|---|', ...rows.map((x) => `| ${x.join(' | ')} |`), '', `DOCX: ${docx}. ${twin}`, `Overall: ${r.pass ? 'all five checks pass' : '**not finished**'}.`, END].join('\n');
}
for (const id of process.argv.slice(2)) {
  const dir = designDir(id), r = readJson(join(SKILL_DIR, 'tests', 'results', `${id.toLowerCase().split('-')[0]}.json`));
  const f = join(dir, 'spec.md'), s = readFileSync(f, 'utf8');
  if (!s.includes(START)) throw new Error(`${f} has no RESULTS block`);
  writeFileSync(f, s.replace(new RegExp(`${START.replace(/[()]/g, '\\$&')}[\\s\\S]*?${END}`), () => table(r)));
  console.log('updated', f);
}
